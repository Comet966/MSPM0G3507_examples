static void i2c_send(const uint8_t *buf, uint16_t len)
{
    gBuf = buf;
    gLen = len;
    gIdx = DL_I2C_fillControllerTXFIFO(I2C_0_INST, (uint8_t *)buf, len);
    if (gIdx < len)
        DL_I2C_enableInterrupt(I2C_0_INST, DL_I2C_INTERRUPT_CONTROLLER_TXFIFO_TRIGGER);
    else
        DL_I2C_disableInterrupt(I2C_0_INST, DL_I2C_INTERRUPT_CONTROLLER_TXFIFO_TRIGGER);
    gSt = I2C_BUSY;
    while (!(DL_I2C_getControllerStatus(I2C_0_INST) & DL_I2C_CONTROLLER_STATUS_IDLE));
    DL_I2C_startControllerTransfer(I2C_0_INST, OLED_ADDR, DL_I2C_CONTROLLER_DIRECTION_TX, len);
    while (gSt == I2C_BUSY) __WFE();
    while (DL_I2C_getControllerStatus(I2C_0_INST) & DL_I2C_CONTROLLER_STATUS_BUSY_BUS);
}

void I2C_0_INST_IRQHandler(void)
{
    switch (DL_I2C_getPendingInterrupt(I2C_0_INST)) {
        case DL_I2C_IIDX_CONTROLLER_TX_DONE:
            DL_I2C_disableInterrupt(I2C_0_INST, DL_I2C_INTERRUPT_CONTROLLER_TXFIFO_TRIGGER);
            gSt = I2C_DONE;
            break;
        case DL_I2C_IIDX_CONTROLLER_TXFIFO_TRIGGER:
            if (gIdx < gLen)
                gIdx += DL_I2C_fillControllerTXFIFO(I2C_0_INST, (uint8_t *)&gBuf[gIdx], gLen - gIdx);
            break;
        case DL_I2C_IIDX_CONTROLLER_NACK:
        case DL_I2C_IIDX_CONTROLLER_ARBITRATION_LOST:
            gSt = I2C_ERR;
            break;
        default: break;
    }
}

