void OLED_init(void)
{
    NVIC_EnableIRQ(I2C_0_INST_INT_IRQN);
    gSt = I2C_IDLE;
    memset(gFb, 0, sizeof(gFb));
    gDirty = 0xFF;
    gCol = 0; gPage = 0;
    delay_cycles(320000);
    i2c_send(gInitSeq, sizeof(gInitSeq));
}

void OLED_clear(void)
{
    memset(gFb, 0, sizeof(gFb));
    gDirty = 0xFF;
}

void OLED_markDirty(void) { gDirty = 0xFF; }

void OLED_display(void)
{
    static uint8_t buf[1 + OLED_WIDTH];
    buf[0] = DATA_BYTE;
    for (uint8_t p = 0; p < OLED_PAGES; p++) {
        if (!(gDirty & (1u << p))) continue;
        uint8_t addr[7] = {CMD_BYTE, 0x21,0x00,0x7F, 0x22,p,p};
        i2c_send(addr, 7);
        memcpy(&buf[1], gFb[p], OLED_WIDTH);
        i2c_send(buf, 1 + OLED_WIDTH);
        gDirty &= ~(1u << p);
    }
}

void OLED_setPixel(uint8_t x, uint8_t y, bool on)
{
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
    uint8_t page = y >> 3, bit = y & 7;
    if (on) gFb[page][x] |=  (1u << bit);
    else    gFb[page][x] &= ~(1u << bit);
    gDirty |= (1u << page);
}

bool OLED_getPixel(uint8_t x, uint8_t y)
{
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return false;
    return (gFb[y >> 3][x] >> (y & 7)) & 1;
}

void OLED_drawLine(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, bool on)
{
    int16_t dx = (x1>x0)?(x1-x0):(x0-x1), dy = (y1>y0)?(y1-y0):(y0-y1);
    int16_t sx = (x0<x1)?1:-1,             sy = (y0<y1)?1:-1;
    int16_t err = dx - dy, cx = x0, cy = y0;
    while (1) {
        OLED_setPixel((uint8_t)cx,(uint8_t)cy,on);
        if (cx==x1 && cy==y1) break;
        int16_t e2 = 2*err;
        if (e2 > -dy) { err -= dy; cx += sx; }
        if (e2 <  dx) { err += dx; cy += sy; }
    }
}

void OLED_drawRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, bool on)
{
    if (!w || !h) return;
    uint8_t x1=x+w-1, y1=y+h-1;
    OLED_drawLine(x,y,x1,y,on); OLED_drawLine(x,y1,x1,y1,on);
    OLED_drawLine(x,y,x,y1,on); OLED_drawLine(x1,y,x1,y1,on);
}

void OLED_fillRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, bool on)
{
    if (!w || !h || x>=OLED_WIDTH || y>=OLED_HEIGHT) return;
    uint8_t xe = (x+w > OLED_WIDTH)  ? OLED_WIDTH  : x+w;
    uint8_t ye = (y+h > OLED_HEIGHT) ? OLED_HEIGHT : y+h;
    uint8_t p0 = y>>3, p1 = (ye-1)>>3;
    for (uint8_t p = p0; p <= p1; p++) {
        uint8_t mask;
        if (p0==p1) {
            mask = ((1u<<(ye-y))-1u) << (y&7);
        } else if (p==p0) {
            mask = 0xFF << (y&7);
        } else if (p==p1) {
            mask = (1u<<((ye-1&7)+1))-1u;
        } else {
            mask = 0xFF;
        }
        for (uint8_t col=x; col<xe; col++) {
            if (on) gFb[p][col] |=  mask;
            else    gFb[p][col] &= ~mask;
        }
        gDirty |= (1u<<p);
    }
}

void OLED_drawCircle(uint8_t cx, uint8_t cy, uint8_t r, bool on)
{
    int16_t x = 0, y = r, d = 1 - r;
    while (x <= y) {
        OLED_setPixel(cx+x,cy+y,on); OLED_setPixel(cx-x,cy+y,on);
        OLED_setPixel(cx+x,cy-y,on); OLED_setPixel(cx-x,cy-y,on);
        OLED_setPixel(cx+y,cy+x,on); OLED_setPixel(cx-y,cy+x,on);
        OLED_setPixel(cx+y,cy-x,on); OLED_setPixel(cx-y,cy-x,on);
        if (d < 0) d += 2*x+3; else { d += 2*(x-y)+5; y--; }
        x++;
    }
}

void OLED_fillCircle(uint8_t cx, uint8_t cy, uint8_t r, bool on)
{
    int16_t x = 0, y = r, d = 1 - r;
    while (x <= y) {
        OLED_fillRect((uint8_t)(cx-x),(uint8_t)(cy-y),(uint8_t)(2*x+1),1,on);
        OLED_fillRect((uint8_t)(cx-x),(uint8_t)(cy+y),(uint8_t)(2*x+1),1,on);
        OLED_fillRect((uint8_t)(cx-y),(uint8_t)(cy-x),(uint8_t)(2*y+1),1,on);
        OLED_fillRect((uint8_t)(cx-y),(uint8_t)(cy+x),(uint8_t)(2*y+1),1,on);
        if (d < 0) d += 2*x+3; else { d += 2*(x-y)+5; y--; }
        x++;
    }
}

void OLED_drawBitmap(uint8_t x, uint8_t y, uint8_t w, uint8_t h,
                     const uint8_t *bmp)
{
    uint8_t pages = (h + 7) >> 3;
    for (uint8_t p = 0; p < pages; p++) {
        uint8_t dp = (y >> 3) + p;
        if (dp >= OLED_PAGES) break;
        uint8_t shift = y & 7;
        for (uint8_t col = 0; col < w; col++) {
            uint8_t dx = x + col;
            if (dx >= OLED_WIDTH) break;
            uint8_t byte = bmp[p * w + col];
            gFb[dp][dx]   |= byte << shift;
            if (shift && dp+1 < OLED_PAGES)
                gFb[dp+1][dx] |= byte >> (8 - shift);
        }
        gDirty |= (1u << dp);
        if (shift && dp+1 < OLED_PAGES) gDirty |= (1u << (dp+1));
    }
}

void OLED_setCursor(uint8_t col, uint8_t page)
{
    gCol  = (col  < OLED_WIDTH/8)  ? col  : 0;
    gPage = (page < OLED_PAGES)    ? page : 0;
}

void OLED_writeChar(char c)
{
    if (c == '\n') { gCol = 0; gPage = (gPage+1) % OLED_PAGES; return; }
    if (c == '\r') { gCol = 0; return; }
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *g = gFont[(uint8_t)(c - 0x20)];
    uint8_t base = gCol * 8;
    for (uint8_t i = 0; i < 8 && base+i < OLED_WIDTH; i++)
        gFb[gPage][base+i] = g[i];
    gDirty |= (1u << gPage);
    if (++gCol >= OLED_WIDTH/8) { gCol = 0; gPage = (gPage+1) % OLED_PAGES; }
}

void OLED_writeString(const char *str)
{
    while (*str) OLED_writeChar(*str++);
}

void OLED_printf(const char *fmt, ...)
{
    char buf[64];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    OLED_writeString(buf);
}
